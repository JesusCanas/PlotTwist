package org.paloma.plottwist.model;

/**
 * Enumeración que define los posibles estados de una serie de televisión.
 * Una serie puede estar en emisión (emitiendo nuevos episodios),
 * finalizada (completada con todos sus episodios) o cancelada (interrumpida).
 * 
 * @author MiguelSg77
 * @version 1.0
 */
public enum Estado {
    EMISION,
    FINALIZADA,
    CANCELADA
}